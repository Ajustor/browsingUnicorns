//! Words shared by several areas: OK, Cancel, Close, Remove…

messages! {
    /// Accepts or dismisses a message.
    fn ok() { en: "OK", fr: "OK" }
    /// Stops what is under way.
    fn cancel() { en: "Cancel", fr: "Annuler" }
    /// Closes a bar or a panel.
    fn close() { en: "Close", fr: "Fermer" }
}
